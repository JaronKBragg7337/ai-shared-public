"""Build ledger: what got built, when, and by which AI, for one usage week (Jaron 10/19: "see everything that's been built by each
AI since 4 o'clock last Wednesday ... since sessions compact, I don't want to rely on what we know in this conversation").
Sources that survive compaction: every git repo under C:\\Users\\lilli\\Projects (commit time, message, Co-Authored-By trailer),
plus AI-Shared/state/timeline.md (AI-Shared isn't a git repo), plus Jaron's usage screenshots logged in state/usage-log.md.
Approximate by design: a fix that took 3 tries is still 1 line; chat itself isn't counted.
   python tools/build_ledger.py            -> current week (from the last Wednesday 4 PM reset)
   python tools/build_ledger.py 2026-10-14 -> the week that started that Wednesday
Writes state/build-ledger/<week-start>.md. Task "HB Build Ledger" refreshes it nightly."""
import os, re, sys, subprocess, datetime, collections

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
PROJECTS = r"C:\Users\lilli\Projects"
RESET_H = 16   # Claude weekly limit resets Wednesday 4 PM Fort Wayne time


def week_start(arg=None):
    if arg: d = datetime.datetime.strptime(arg, "%Y-%m-%d").replace(hour=RESET_H)
    else:
        now = datetime.datetime.now(); d = now.replace(hour=RESET_H, minute=0, second=0, microsecond=0)
        d -= datetime.timedelta(days=(d.weekday() - 2) % 7)
        if d > now: d -= datetime.timedelta(days=7)
    return d


# Who made it. The trailer is right for builds; daily capture scripts sign as Claude though another AI wrote the content.
BY_MESSAGE = [(r"^watch: codex", "Codex (daily capture)"), (r"^watch: grok", "Grok (daily capture)"), (r"^watch: deepseek", "DeepSeek (daily capture)"),
              (r"^watch: kimi", "Kimi (daily capture)"), (r"^watch: qwen", "Qwen (daily capture)"), (r"^news: episode|^news episode", "News writer (daily)")]


def who(trailer, msg, repo):
    for pat, name in BY_MESSAGE:
        if re.search(pat, msg, re.I): return name
    t = trailer.lower()
    for key, name in (("fable", "Claude Fable"), ("sonnet", "Claude Sonnet"), ("opus", "Claude Opus"), ("codex", "Codex"), ("gpt", "Codex"),
                      ("grok", "Grok Build"), ("kimi", "Kimi"), ("deepseek", "DeepSeek"), ("qwen", "Qwen")):
        if key in t: return name
    if repo == "sapling": return "unsigned (Sapling: Kimi teaches it since 10/16)"
    return "unsigned"


def commits(since, until):
    out = []
    for d in sorted(os.listdir(PROJECTS)):
        p = os.path.join(PROJECTS, d)
        if not os.path.isdir(os.path.join(p, ".git")): continue
        r = subprocess.run(["git", "-C", p, "log", "--since=" + since.isoformat(), "--until=" + until.isoformat(),
                            "--format=%ad\x1f%(trailers:key=Co-Authored-By,valueonly,separator=;)\x1f%s\x1e", "--date=iso-local"],
                           capture_output=True, text=True, encoding="utf-8", errors="replace")
        for rec in r.stdout.split("\x1e"):
            rec = rec.strip()
            if not rec: continue
            when, trailer, msg = (rec.split("\x1f") + ["", ""])[:3]
            out.append((datetime.datetime.fromisoformat(when.strip()[:19]), d, who(trailer, msg, d), msg.strip()))
    return out


def timeline(since, until):
    out = []
    path = os.path.join(ROOT, "state", "timeline.md")
    if not os.path.exists(path): return out
    for l in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r"- (\d{4}-\d\d-\d\d)(?: (\d\d?:\d\d))?\s+(.*)", l.strip())
        if not m: continue
        try: t = datetime.datetime.strptime(m[1] + " " + (m[2] or "12:00"), "%Y-%m-%d %H:%M")
        except ValueError: continue
        if since <= t < until: out.append((t, m[3]))
    return out


def usage(since, until):
    path = os.path.join(ROOT, "state", "usage-log.md"); out = []
    if not os.path.exists(path): return out
    for l in open(path, encoding="utf-8"):
        m = re.match(r"\| (\d{4}-\d\d-\d\d \d\d:\d\d) \|(.*)", l)
        if m:
            t = datetime.datetime.strptime(m[1], "%Y-%m-%d %H:%M")
            if since <= t < until: out.append((t, m[2].strip(" |")))
    return out


def main():
    s = week_start(sys.argv[1] if len(sys.argv) > 1 else None); e = s + datetime.timedelta(days=7)
    cs = commits(s, e); tl = timeline(s, e); us = usage(s, e)
    per = collections.Counter(c[2] for c in cs)
    md = [f"# Build ledger: week of {s:%a %b %d} 4 PM -> {e:%a %b %d} 4 PM", "",
          "Generated by tools/build_ledger.py from git history + state/timeline.md + state/usage-log.md (approximate: chat isn't counted, "
          "a fix that took several tries is one line).", "", "## Per AI (commits)", "", "| Who | Commits |", "|---|---|"]
    md += [f"| {k} | {v} |" for k, v in per.most_common()]
    if us:
        md += ["", "## Usage snapshots (from Jaron's screenshots)", "", "| When | Reading |", "|---|---|"] + [f"| {t:%a %m-%d %H:%M} | {r} |" for t, r in us]
    md += ["", "## Day by day", ""]
    days = sorted({c[0].date() for c in cs} | {t.date() for t, _ in tl})
    for d in days:
        md.append(f"### {d:%a %b %d}")
        dc = [c for c in cs if c[0].date() == d and "daily capture" not in c[2] and "daily)" not in c[2]]
        auto = collections.Counter(c[2] for c in cs if c[0].date() == d and ("daily capture" in c[2] or "daily)" in c[2]))
        for t, repo, w, msg in sorted(dc):
            md.append(f"- {t:%H:%M} **{w}** [{repo}] {msg[:160]}")
        if auto: md.append("- automatic: " + ", ".join(f"{k} x{v}" for k, v in auto.items()))
        notes = [(t, x) for t, x in tl if t.date() == d]
        if notes:
            md.append("- notes (state/timeline.md, AI-Shared work with no git):")
            md += [f"  - {t:%H:%M} {x[:200]}" for t, x in sorted(notes)]
        md.append("")
    os.makedirs(os.path.join(ROOT, "state", "build-ledger"), exist_ok=True)
    out = os.path.join(ROOT, "state", "build-ledger", f"{s:%Y-%m-%d}.md")
    open(out, "w", encoding="utf-8").write("\n".join(md) + "\n")
    print(out, len(cs), "commits,", len(tl), "notes,", len(us), "usage snapshots")
    print("\n".join(md[6:6 + len(per) + 3]))


if __name__ == "__main__":
    main()
